import { chromium, devices } from "playwright";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
const bad = [];
page.on("response", r => { if (r.status() >= 400) bad.push(r.status() + " " + r.url().slice(0, 120)); });
await page.goto("https://fomal258.github.io/fomal/?v=4", { waitUntil: "load" });
await page.waitForSelector(".card-shell", { timeout: 40000 });
await page.waitForTimeout(2500);
console.log("bad responses:", bad.length);
bad.slice(0, 8).forEach(b => console.log("  ", b));
await browser.close();
