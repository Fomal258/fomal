import { chromium, devices } from "playwright";
const base = "file://" + process.cwd().replace(/\/source$/, "") + "/index.html";
const browser = await chromium.launch();
const ctx = await browser.newContext({ ...devices["iPhone 13"] });
const page = await ctx.newPage();
const logs = [];
page.on("pageerror", e => logs.push("pageerror: " + e.message));
page.on("console", m => logs.push(m.type() + ": " + m.text().slice(0, 140)));
await page.goto(base);
await page.waitForSelector(".card-shell", { timeout: 30000 });
console.log("__ghQuick:", await page.evaluate(() => Boolean(window.__ghQuick)), "| __mobileUx:", await page.evaluate(() => Boolean(window.__mobileUx)));
console.log("script tags:", await page.evaluate(() => [...document.querySelectorAll("script")].map(s => s.id || s.type || "inline").join(",")));
await page.click('.mobile-dock button[data-act="sync"]');
await page.waitForTimeout(1500);
console.log("modals:", await page.evaluate(() => document.querySelectorAll(".gh-sync-modal").length), "| any modal:", await page.evaluate(() => document.querySelectorAll(".editor-modal").length));
console.log("panel:", await page.evaluate(() => document.querySelectorAll(".gh-quick").length));
console.log("logs:", logs.slice(0, 6));
await browser.close();
