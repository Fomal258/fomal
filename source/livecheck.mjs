import { chromium } from "playwright";
const base = "https://fomal258.github.io/fomal/";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 1100 } });
const errs = [];
page.on("pageerror", e => errs.push(e.message));
page.on("console", m => { if (m.type() === "error") errs.push(m.text().slice(0, 120)); });
await page.goto(base, { waitUntil: "load" });
await page.waitForSelector(".card-shell", { timeout: 30000 });
console.log("live cards:", await page.locator(".card-shell").count());
await page.fill('input[aria-label="선수 검색"]', "man");
await page.waitForTimeout(800);
console.log("search url:", page.url().split("?")[1] || "(none)", "| cards:", await page.locator(".card-shell").count(), "| reset:", await page.locator(".filter-reset").isVisible());
await page.click(".filter-reset");
await page.waitForTimeout(500);
await page.screenshot({ path: "../live-desktop.png" });

await page.goto(base + "?p=1-called-manders", { waitUntil: "load" });
await page.waitForSelector(".info-modal", { timeout: 30000 });
console.log("deep link:", await page.locator("#profile-info-title").innerText(), "| actions:", (await page.locator(".info-actions").innerText()).replace(/\s+/g, " "));
await page.screenshot({ path: "../live-profile.png" });
console.log("errors:", errs.length ? errs.slice(0, 3) : "none");
await browser.close();
